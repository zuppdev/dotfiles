#!/usr/bin/env python3
"""Derive a SketchyBar palette from the wallpaper strip behind the bar.

Keeps the wallpaper's hue, but forces the pill away from the background and
picks ink for guaranteed contrast. Every value is verified, not assumed.
"""
import colorsys, subprocess, sys, pathlib

MIN_TEXT = 4.5   # accessibility.md: text up to 17pt
MIN_PILL = 3.0   # pill must be distinguishable from the wallpaper

def lin(c):
    c /= 255.0
    return c/12.92 if c <= 0.03928 else ((c+0.055)/1.055)**2.4
def lum(rgb):
    r,g,b = rgb
    return 0.2126*lin(r)+0.7152*lin(g)+0.0722*lin(b)
def ratio(a,b):
    la,lb = lum(a),lum(b); hi,lo = max(la,lb),min(la,lb)
    return (hi+0.05)/(lo+0.05)
def hexs(rgb): return "%02x%02x%02x" % tuple(max(0,min(255,int(v))) for v in rgb)
def unhex(h):
    h=h.lstrip('#'); return (int(h[0:2],16),int(h[2:4],16),int(h[4:6],16))
def with_l(rgb, L, S=None):
    r,g,b = [v/255 for v in rgb]
    h,_,s = colorsys.rgb_to_hls(r,g,b)
    if S is not None: s = S
    r,g,b = colorsys.hls_to_rgb(h, L, s)
    return (r*255, g*255, b*255)

def fit(base, target_bg, minr, start, step):
    """Walk lightness until `base` clears `minr` against target_bg."""
    L = start
    for _ in range(60):
        c = with_l(base, L)
        if ratio(c, target_bg) >= minr:
            return c
        L += step
        if not (0.0 <= L <= 1.0): break
    return with_l(base, max(0.0, min(1.0, L)))

def main():
    strip_hex, strip_lum = sys.argv[1], float(sys.argv[2])
    wall = unhex(strip_hex)
    dark_wall = strip_lum <= 0.40

    # Pill moves AWAY from the wallpaper; ink moves away from the pill.
    if dark_wall:
        pill = with_l(wall, 0.78, S=0.45)      # light pill on dark wallpaper
        ink_dir, ink_start = -0.02, 0.30
    else:
        pill = with_l(wall, 0.16, S=0.35)      # dark pill on light wallpaper
        ink_dir, ink_start = +0.02, 0.70
    pill = fit(pill, wall, MIN_PILL, 0.78 if dark_wall else 0.16, 0.02 if dark_wall else -0.02)
    ink  = fit(pill, pill, 0, 0, 0)            # placeholder, replaced below
    ink  = fit(with_l(wall, ink_start, S=0.12), pill, MIN_TEXT, ink_start, ink_dir)

    # Rosé Pine accents, each fitted to the pill
    ROSE_PINE = {
        "red":"#eb6f92", "green":"#9ccfd8", "blue":"#3e8fb0",
        "yellow":"#f6c177", "orange":"#ea9a97", "magenta":"#c4a7e7",
    }
    accents = {}
    for name, hx in ROSE_PINE.items():
        base = unhex(hx)
        start = 0.72 if not dark_wall else 0.40
        direction = +0.02 if not dark_wall else -0.02
        accents[name] = fit(base, pill, MIN_TEXT, start, direction)

    dim = fit(ink, pill, MIN_TEXT, 0.62 if not dark_wall else 0.38, ink_dir)

    out = [
        "-- GENERATED by helpers/wallpaper_theme.py - do not hand-edit.",
        "-- Derived from the wallpaper strip directly behind the bar.",
        f"-- wallpaper strip #{strip_hex} (luminance {strip_lum:.3f}) -> "
        f"{'light pill on dark wallpaper' if dark_wall else 'dark pill on light wallpaper'}",
        f"-- pill vs wallpaper {ratio(pill,wall):.2f}:1 | ink vs pill {ratio(ink,pill):.2f}:1",
        "return {",
        f'  pill = 0xff{hexs(pill)},',
        f'  ink  = 0xff{hexs(ink)},',
        f'  dim  = 0xff{hexs(dim)},',
    ]
    for name, rgb in accents.items():
        out.append(f'  {name} = 0xff{hexs(rgb)},   -- {ratio(rgb,pill):.2f}:1')
    out.append("}")
    pathlib.Path(sys.argv[3]).write_text("\n".join(out) + "\n")

    print(f"  wallpaper strip #{strip_hex} lum={strip_lum:.3f} ({'dark' if dark_wall else 'light'})")
    print(f"  pill #{hexs(pill)}  vs wallpaper {ratio(pill,wall):.2f}:1  (need >={MIN_PILL})")
    print(f"  ink  #{hexs(ink)}   vs pill      {ratio(ink,pill):.2f}:1  (need >={MIN_TEXT})")
    print(f"  dim  #{hexs(dim)}   vs pill      {ratio(dim,pill):.2f}:1")
    for name, rgb in accents.items():
        print(f"  {name:8} #{hexs(rgb)}  {ratio(rgb,pill):.2f}:1")

main()
